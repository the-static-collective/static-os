"""Offline printable HOUSE-SEED work cards. Strictly read-only: HTML from verified plan."""
from html import escape

from suitcase.house import verify_house

def e(value):
    return escape(str(value), quote=True)

def render_house(plan):
    verify_house(plan)
    stages = []
    for step in plan['stages']:
        stages.append(f'''<section class="step"><h2>STAGE {e(step['id'])} / {e(step['name'].replace('_', ' '))}</h2>
<p>{e(step['work'])}</p><p><strong>Evidence:</strong> {e(step['evidence'])}</p>
<p>□ Reviewed by human &nbsp; □ Test recorded &nbsp; □ Refused or deferred</p></section>''')
    modules = []
    for mod in plan['modules']:
        parts = ', '.join(f"{e(part)} ({e(mod['part_observations'][part])})" for part in mod['required_parts'])
        holds = ', '.join(e(h) for h in mod['holds']) or 'None from survey (not permission or proof)'
        modules.append(f'''<section class="module"><h3>{e(mod['id'].replace('_', ' '))} <small>{e(mod['state'])}</small></h3>
<p>{e(mod['purpose'])}</p><p><b>Proposed site:</b> {e(mod['placement_candidate'])}</p>
<p><b>Parts:</b> {parts}</p><p><b>Outstanding survey gaps:</b> {holds}</p>
<p><b>Measure:</b> {e(mod['test_receipt_to_collect'])}</p>
<p>□ Not started &nbsp; □ Failed &nbsp; □ Human observed (attach independent receipt)</p></section>''')
    return f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'">
<meta name="referrer" content="no-referrer"><title>Living House · Suitcase Work Cards</title>
<style>
body{{font-family:system-ui,sans-serif;background:#f6f4eb;color:#1d2826;max-width:900px;margin:auto;padding:2rem;line-height:1.55}}
h1{{font-size:2.1rem;line-height:1.1}}h2{{font-size:1.25rem}}h3{{font-size:1.15rem}}
header{{border:3px solid #314c38;padding:1rem 1.3rem}}.stamp{{font-weight:800;color:#8b3434;letter-spacing:.07em}}
.step,.module{{border:1px solid #7b9185;padding:1rem 1.2rem;margin:1.1rem 0;break-inside:avoid;background:white}}
small{{display:block;font-size:.75rem;font-weight:500;color:#874343}}
code{{overflow-wrap:anywhere}}.limit{{border-left:6px solid #8b3434;padding:1rem;background:#fff9f0}}
@media print{{body{{margin:0;max-width:none;padding:0;color:black;background:white}}header,.step,.module{{break-inside:avoid}}}}
</style></head><body>
<header><p class="stamp">HOLD ONLY · NOT AN INSTALLER · NOT A CONSTRUCTION PERMIT</p>
<h1>The Living House: Build Work Cards</h1>
<p>One house as the smallest model of a cooperative city, generated by an independently controlled Suitcase.</p>
<p><b>Proposal SHA-256:</b> <code>{e(plan['plan_sha256'])}</code></p>
<p><b>Site class:</b> {e(plan['site_survey']['building_type'])} · <b>Reported site permission:</b> {e(plan['site_survey']['site_permission'])}</p></header>
<h2>What the Suitcase proposes, not what exists</h2>
<p>Site observations are self-reported and public-safe. An observed part is unverified. No apparatus is activated by this document. Power, roof, wiring, plumbing, structure, radio and public infrastructure require separate review and permission.</p>
<h2>Five stages</h2>{''.join(stages)}
<h2>House organs / parts / independent test receipts</h2>{''.join(modules)}
<div class="limit"><b>Not earned:</b> {e('; '.join(plan['claims_not_earned']))}
<p>No names, secret keys, private addresses, survivor records or live client data. No voice-controlled access, safety-critical systems or active discovery. A second consented node may refuse all requests and retains its own key and governance.</p></div>
<p>Bench operator (optional paper signature): ________________________ Date: ___________</p>
<p>Independent witness (if any): ____________________________ Outcome: _______________</p>
<p><b>Printed cards are not signed evidence.</b> Keep original raw measurements and independent receipts. File made entirely offline from a cold-verified JSON proposal.</p></body></html>'''
